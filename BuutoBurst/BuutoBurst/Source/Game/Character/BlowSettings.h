#pragma once

// 吹っ飛ばされ値の決まり プレイヤーは PlayerData、敵は EnemyData に 1 つずつ持つ
//
// 攻撃が当たるたびに、その技のダメージの分だけ値が溜まる 場の真ん中で当てても溜まり、体に残る
// 溜まるほど遠くへ飛ぶ 当たらない間は少しずつ減る (吹き飛んでいる間は減らない)
// 溜まり具合は数字では見せず、体の赤みと立ちのぼる湯気で見せる
// 許容値に届くと、弱い攻撃でも吹き飛ぶようになり、その勢いで壁にぶつかると壁が割れる (ArenaWall)
struct BlowSettings {
    // 許容値 赤みと湯気は、値がこれに近づくほど強くなる
    float limit = 100.0f;

    // 値が許容値に届いたときに、吹っ飛ぶ速さが何倍増えるか 1 なら 2 倍になる
    float growth = 1.0f;

    // 最後に当たってから (吹き飛んでいたら着地してから) 減り始めるまで 秒
    float recoverDelay = 1.0f;

    // 減り始めたら、1 秒に許容値のこの割合ずつ減る
    float recoverRate = 0.08f;

    // 吹き飛んで起き上がったときに、許容値のこの割合だけ減る
    float getUpRecoverRate = 0.15f;
};
